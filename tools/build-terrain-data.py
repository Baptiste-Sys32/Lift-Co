from pathlib import Path
from concurrent.futures import ThreadPoolExecutor
from urllib.request import urlopen
from PIL import Image
from io import BytesIO
import numpy as np
import math,json,base64
from datetime import date
root=Path(__file__).resolve().parents[1]
cache=Path('/tmp/lift-elevation-cache');cache.mkdir(exist_ok=True)
lat0,lon0=45.399,6.624
zoom=13;n=2**zoom;meters_lat=111132.;meters_lon=111320.*math.cos(math.radians(lat0))
def pixel(lat,lon):return ((lon+180)/360*n*256,(1-math.asinh(math.tan(math.radians(lat)))/math.pi)/2*n*256)
width,depth=3200,3800
context_width,context_depth=7200,7800
lat_min=lat0-context_depth/2/meters_lat;lat_max=lat0+context_depth/2/meters_lat
lon_min=lon0-context_width/2/meters_lon;lon_max=lon0+context_width/2/meters_lon
left,top=pixel(lat_max,lon_min);right,bottom=pixel(lat_min,lon_max)
xmin,xmax=int(left//256),int(right//256);ymin,ymax=int(top//256),int(bottom//256)
coords=[(x,y)for y in range(ymin,ymax+1)for x in range(xmin,xmax+1)]
def fetch(pair):
 x,y=pair;file=cache/f'{zoom}-{x}-{y}.png'
 if not file.exists():
  with urlopen(f'https://s3.amazonaws.com/elevation-tiles-prod/terrarium/{zoom}/{x}/{y}.png',timeout=40)as response:file.write_bytes(response.read())
 a=np.array(Image.open(file).convert('RGB'),dtype=np.float32)
 return x,y,a[:,:,0]*256+a[:,:,1]+a[:,:,2]/256-32768
with ThreadPoolExecutor(max_workers=6)as pool:tiles=list(pool.map(fetch,coords))
image=np.zeros(((ymax-ymin+1)*256,(xmax-xmin+1)*256),dtype=np.float32)
for x,y,tile in tiles:image[(y-ymin)*256:(y-ymin+1)*256,(x-xmin)*256:(x-xmin+1)*256]=tile
# Resample with geographic metre spacing; all terrain elevations remain data-derived.
def sample_grid(w,d,columns,rows):
 x=np.linspace(-w/2,w/2,columns);z=np.linspace(-d/2,d/2,rows)
 lon=lon0+x/meters_lon;lat=lat0+z/meters_lat
 px=(lon+180)/360*n*256-xmin*256
 py=(1-np.arcsinh(np.tan(np.radians(lat)))/np.pi)/2*n*256-ymin*256
 xx,yy=np.meshgrid(px,py);ix=np.floor(xx).astype(int);iy=np.floor(yy).astype(int);fx=xx-ix;fy=yy-iy
 return (image[iy,ix]*(1-fx)*(1-fy)+image[iy,ix+1]*fx*(1-fy)+image[iy+1,ix]*(1-fx)*fy+image[iy+1,ix+1]*fx*fy)
core=sample_grid(width,depth,321,381)
context=sample_grid(context_width,context_depth,241,261)
# 0.1m quantization preserves the supplied data without shipping a large JSON number array.
def encode(grid):return base64.b64encode(np.round(grid*10).astype('<u2').tobytes()).decode()
meta={'name':'Saulire / Courchevel','latitude':lat0,'longitude':lon0,'width':width,'depth':depth,'columns':321,'rows':381,'contextWidth':context_width,'contextDepth':context_depth,'contextColumns':241,'contextRows':261,'originElevation':math.floor(float(context.min())/100)*100,'minElevation':round(float(core.min()),1),'maxElevation':round(float(core.max()),1),'quantization':.1,'source':'Mapzen Terrain Tiles','sourceURL':'https://registry.opendata.aws/terrain-tiles/','attributionURL':'https://github.com/tilezen/joerd/blob/master/docs/attribution.md','accessed':date.today().isoformat(),'zoom':zoom,'processing':'Terrarium RGB decoding; geographic bilinear resampling; 0.1 m quantization. No vertical exaggeration or generated height detail.'}
(root/'assets/data/terrain-heightmap.js').write_text('// Fixed Alpine elevation data; generated by tools/build-terrain-data.py.\nwindow.LIFT_TERRAIN_DATA='+json.dumps({**meta,'heights':encode(core),'contextHeights':encode(context)},separators=(',',':'))+';\n')
(root/'assets/data/terrain-sources.json').write_text(json.dumps(meta,indent=2)+'\n')
np.save('/tmp/lift-alpine-core.npy',core)
np.save('/tmp/lift-alpine-context.npy',context)
print(json.dumps({**meta,'downloadedTiles':len(tiles)},indent=2))
